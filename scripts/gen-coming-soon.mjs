// @ts-check
/**
 * Generates a standardized Coming Soon page for every tool marked
 * `status: "soon"` in lib/tools-registry.ts.
 *
 * Each generated page is a thin server component that derives its metadata
 * from the registry and renders the shared <ComingSoonTool>. Live tools (with
 * their own hand-written client) are never touched — we only ever create pages
 * for soon slugs, and only overwrite pages that are themselves Coming Soon
 * stubs.
 *
 * Run:  node scripts/gen-coming-soon.mjs
 */
import { readFileSync, writeFileSync, mkdirSync, existsSync, readdirSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const registryPath = join(root, "lib", "tools-registry.ts");
const toolsDir = join(root, "app", "tools");

// ── Parse soon slugs out of the registry ───────────────────────────────
const src = readFileSync(registryPath, "utf8");
const slugRe = /slug:\s*"([^"]+)"/g;
const slugs = [];
let match;
while ((match = slugRe.exec(src)) !== null) {
  const slug = match[1];
  // Look at this tool object only, up to the next slug declaration.
  const nextSlug = src.indexOf('slug:', slugRe.lastIndex);
  const block = src.slice(slugRe.lastIndex, nextSlug === -1 ? undefined : nextSlug);
  if (/status:\s*"soon"/.test(block)) slugs.push(slug);
}

const template = (slug) => `import type { Metadata } from "next";
import { getTool } from "@/lib/tools-registry";
import { ToolPage } from "@/components/tool/tool-page";
import { ComingSoonTool } from "@/components/tool/coming-soon-tool";

// Auto-generated by scripts/gen-coming-soon.mjs — safe to regenerate.
const SLUG = "${slug}";
const tool = getTool(SLUG);

export const metadata: Metadata = {
  title: tool?.name ?? "OmniTools",
  description: tool ? \`\${tool.description} 100% in your browser — no uploads.\` : undefined,
};

export default function Page() {
  return (
    <ToolPage slug={SLUG}>
      <ComingSoonTool slug={SLUG} />
    </ToolPage>
  );
}
`;

/** A dir is a Coming Soon stub (safe to overwrite) if its page imports ComingSoonTool. */
function isStub(slug) {
  const page = join(toolsDir, slug, "page.tsx");
  if (!existsSync(page)) return true; // nothing there yet → create
  return readFileSync(page, "utf8").includes("ComingSoonTool");
}

let created = 0;
let skipped = 0;
for (const slug of slugs) {
  const dir = join(toolsDir, slug);
  if (!isStub(slug)) {
    // A hand-written live client lives here — never clobber it.
    console.log(`skip (live)  ${slug}`);
    skipped++;
    continue;
  }
  mkdirSync(dir, { recursive: true });
  writeFileSync(join(dir, "page.tsx"), template(slug), "utf8");
  created++;
}

// Report any live tool dirs that lack a page, as a sanity check.
const existingDirs = readdirSync(toolsDir, { withFileTypes: true })
  .filter((d) => d.isDirectory())
  .map((d) => d.name);

console.log(
  `\nGenerated ${created} Coming Soon page(s), skipped ${skipped}. ` +
    `${slugs.length} soon slugs, ${existingDirs.length} tool dirs on disk.`,
);
